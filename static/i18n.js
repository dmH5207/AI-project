window.currentLang = localStorage.getItem("lang") || "zh";

window.t = function (key) {
  return (window.I18N[window.currentLang] || window.I18N.zh)[key] || key;
};

window.applyLang = function () {
  document.documentElement.lang = window.currentLang;
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    var key = el.getAttribute("data-i18n");
    el.textContent = window.t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = window.t(key);
  });
  var toggle = document.getElementById("langToggle");
  if (toggle) toggle.classList.toggle("en", window.currentLang === "en");
  document.querySelectorAll(".lang-label").forEach(function (el) {
    el.classList.toggle("active", el.getAttribute("data-lang") === window.currentLang);
  });
};

window.setLang = function (lang) {
  window.currentLang = lang;
  localStorage.setItem("lang", lang);
  window.applyLang();
  window.dispatchEvent(new Event("langChanged"));
};

window.toggleLang = function () {
  window.setLang(window.currentLang === "zh" ? "en" : "zh");
};